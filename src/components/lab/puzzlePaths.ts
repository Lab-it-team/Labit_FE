export function getPuzzlePath(ion: Ion): string {
  const c = Math.abs(ion.charge);
  if (ion.type === "minus") {
    if (c >= 3) return PATH_ANION_300;
    if (c >= 2) return PATH_ANION_200;
    return PATH_ANION_100;
  }
  if (c >= 3) return PATH_CATION_300;
  if (c >= 2) return PATH_CATION_200;
  return PATH_CATION_100;
}

export function cardHeight(ion: Ion): number {
  const c = Math.abs(ion.charge);
  if (c >= 3) return 300;
  if (c >= 2) return 200;
  return 100;
}

export function ionColor(ion: Ion): string {
  const c = Math.abs(ion.charge);
  if (ion.type === "minus") {
    if (c >= 3) return "var(--color-element-normal-violet)";
    if (c >= 2) return "var(--color-element-normal-blue)";
    return "var(--color-element-normal-mint)";
  }
  if (c >= 3) return "var(--color-element-normal-orange)";
  if (c === 1) return "var(--color-element-normal-pink)";
  return "var(--color-element-normal-yellow)";
}
